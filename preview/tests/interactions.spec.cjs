const { test, expect } = require('@playwright/test');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const url = pathToFileURL(path.resolve(__dirname, '../../visualizar-becake.html')).href;
test('portable site: filters, accessible lightbox and pause', async ({ page }) => {
  await page.goto(url);
  await expect(page.locator('.intro')).toHaveCount(0);
  await page.getByRole('button', { name: 'Doces de Celebração', exact: true }).click();
  await expect(page.locator('.features .card:visible')).toHaveCount(1);
  await expect(page.locator('.features .card:visible h3')).toHaveText('Doces de celebração');
  await page.getByRole('button', { name: 'Todas', exact: true }).click();
  await expect(page.locator('.features .card:visible')).toHaveCount(3);
  const photo = page.locator('.photo-tile:visible').first();
  await photo.click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await expect(page.getByRole('button', { name: 'Fechar imagem ampliada' })).toBeFocused();
  await page.keyboard.press('ArrowRight');
  await expect(dialog.locator('.lightbox-count')).toHaveText('2 de 10');
  const href = await page.getByRole('link', { name: 'Quero uma opção assim' }).getAttribute('href');
  expect(new URL(href).hostname).toBe('wa.me');
  expect(new URL(href).searchParams.get('text')).toContain('Bolo com flores rosa e douradas');
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.photo-tile').nth(1)).toBeFocused();
  await page.getByRole('button', { name: 'Ver mais criações' }).click();
  await expect(page.locator('.photo-tile:visible')).toHaveCount(25);
  await expect(page.locator('#depoimentos')).toBeHidden();
  await expect(page.locator('.review-content')).toBeHidden();
});
